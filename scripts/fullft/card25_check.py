"""Plan v21 card 25 generator check (11-27 02:30, Opus; written before any card 25 scene exists). Read-only, CPU.
Input: <base>/t<K>/demo_clean/observe_and_pickup/aloha_agilex/ for K = 0..4, each generated by
`fastwam.memory_v2.online gen --gen-seeds <the same seeds> --gen-target K` (gen_demos.py's target hook).
The card's checks (plan v21 6.3), all four must pass before anything is generated for training:
  1 the target can be fixed: in targets.jsonl every planned seed with more than K candidates has target_object_idx == K
    (the hook returned K; the benchmark's own draw is kept in 'drawn');
  2 the same seed with different targets gives the same table: frame 0, head camera outside the shelf box (REF_BOX), and
    both wrist cameras: the largest pixel difference between target 0's episode and target K's (reported exactly; the
    gate is "pixel-identical": max |diff| == 0; if the renderer is not bit-deterministic run to run, the numbers are
    reported and the check FAILS -> report to the user, nothing goes into training); the shelf box must differ whenever
    the two targets are different object instances (reported);
  3 the scripted expert succeeds on >= 90 % of the seeds for EVERY target (seeds with too few candidates excluded);
  4 card 8's render gate (gen_check.py --gate background on the official seeds 0-2) is re-run by the runner script with
    the current code (its result file is read here).
Prints CARD25 CHECK PASS / FAIL; JSON -> outputs/fullft/gen_cf/CARD25_CHECK.json
  PYTHONPATH=src /opt/mwam/bin/python scripts/fullft/card25_check.py --base outputs/fullft/gen_cf/check
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "scripts/memory_v2/press"))
REF_BOX = (0.395, 0.06, 0.675, 0.34)
TASK = "observe_and_pickup"


def tdir(base, k):
    return Path(base) / f"t{k}" / "demo_clean" / TASK / "aloha_agilex"


def seed_to_episode(d: Path):
    seeds = [int(x) for x in (d / "seed.txt").read_text().split()] if (d / "seed.txt").exists() else []
    return {s: d / "data" / f"episode_{i:07d}.hdf5" for i, s in enumerate(seeds) if (d / "data" / f"episode_{i:07d}.hdf5").exists()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--targets", type=int, default=5)
    ap.add_argument("--render", default="/workspace/FastWAM-memory2/outputs/fullft/gen_cf/GEN_CHECK_RENDER.json")
    ap.add_argument("--out", default="/workspace/FastWAM-memory2/outputs/fullft/gen_cf/CARD25_CHECK.json")
    a = ap.parse_args()
    rep = {"base": a.base, "checks": {}}
    # 1 + 3
    fixed_ok, rates = True, {}
    for k in range(a.targets):
        d = tdir(a.base, k)
        lines = [json.loads(x) for x in (d / "targets.jsonl").read_text().splitlines() if x.strip()] \
            if (d / "targets.jsonl").exists() else []
        plan = [x for x in lines if x["phase"] == "plan"]
        possible = [x for x in plan if not x["missing"]]
        bad = [x for x in possible if x["target_object_idx"] != k]
        fixed_ok = fixed_ok and bool(possible) and not bad
        ok_seeds = set(seed_to_episode(d))
        tried = {x["seed"] for x in possible}
        rate = len(ok_seeds & tried) / max(1, len(tried))
        rates[k] = {"seeds_tried": len(tried), "expert_success": len(ok_seeds & tried), "rate": round(rate, 3),
                    "too_few_candidates": sum(x["missing"] for x in plan), "target_not_forced": len(bad),
                    "drawn_equals_forced": sum(x["drawn"] == k for x in possible)}
    rep["checks"]["1_target_fixed"] = {"pass": fixed_ok, "per_target": rates}
    rep["checks"]["3_expert_success_per_target"] = {"pass": all(r["rate"] >= 0.90 and r["seeds_tried"] > 0 for r in rates.values()),
                                                     "rates": {k: r["rate"] for k, r in rates.items()}}
    # 2
    import build_dense as bd
    common, data_path = bd.setup()
    cfg = json.loads((Path("/workspace/FastWAM-memory2/outputs/memory_v2/press") / f"dense_{TASK}_v1" / "IDENTITY.json").read_text())["config"]
    maps = [seed_to_episode(tdir(a.base, k)) for k in range(a.targets)]
    seeds = sorted(set(maps[0]).intersection(*[set(m) for m in maps[1:]]))
    pix = []
    for s in seeds:
        frames = []
        for k in range(a.targets):
            rec = bd.make_record(common, maps[k][s], TASK, "train")
            raw = data_path.Raw(cfg, rec)
            try:
                frames.append([np.asarray(x).astype(np.int16) for x in raw.images(0)])
            finally:
                raw.close()
        for k in range(1, a.targets):
            row = {"seed": s, "target": k}
            for c, (x, y) in enumerate(zip(frames[0], frames[k])):
                d = np.abs(x - y).max(axis=-1)
                if c == 0:
                    h, w = d.shape
                    box = np.zeros(d.shape, bool)
                    box[int(REF_BOX[1] * h):int(REF_BOX[3] * h), int(REF_BOX[0] * w):int(REF_BOX[2] * w)] = True
                    row["head_outside_shelf_max"] = int(d[~box].max())
                    row["head_outside_shelf_nonzero"] = round(float((d[~box] > 0).mean()), 6)
                    row["shelf_box_differs"] = bool((d[box] > 8).mean() > 0.01)
                else:
                    row[f"wrist{c}_max"] = int(d.max())
            pix.append(row)
    same = bool(pix) and all(r["head_outside_shelf_max"] == 0 and all(v == 0 for kk, v in r.items() if kk.startswith("wrist"))
                             for r in pix)
    rep["checks"]["2_same_table"] = {"pass": same, "seeds_compared": len(seeds), "pairs": pix,
                                     "shelf_differs_in": sum(r["shelf_box_differs"] for r in pix)}
    # 4
    rend = json.loads(Path(a.render).read_text()) if Path(a.render).exists() else {}
    rep["checks"]["4_card8_render_gate"] = {"pass": bool(rend.get("pass")), "gate": rend.get("gate"), "file": a.render}
    ok = all(c["pass"] for c in rep["checks"].values())
    rep["pass"] = ok
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(rep, indent=1) + "\n")
    for name, c in rep["checks"].items():
        brief = {k: v for k, v in c.items() if k not in ("pairs",)}
        print(f"[card25] {name}: {json.dumps(brief)[:600]}")
    print("CARD25 CHECK " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
